-- Bucket public pour les fichiers de galerie
insert into storage.buckets (id, name, public)
values ('photos', 'photos', true)
on conflict (id) do nothing;

drop policy if exists "Public read access to photos bucket" on storage.objects;
drop policy if exists "Custom admin upload to photos bucket" on storage.objects;
drop policy if exists "Custom admin update on photos bucket" on storage.objects;
drop policy if exists "Custom admin delete on photos bucket" on storage.objects;

create policy "Public read access to photos bucket"
on storage.objects
for select
using (bucket_id = 'photos');

create policy "Custom admin upload to photos bucket"
on storage.objects
for insert
with check (bucket_id = 'photos' and true);

create policy "Custom admin update on photos bucket"
on storage.objects
for update
using (bucket_id = 'photos' and true);

create policy "Custom admin delete on photos bucket"
on storage.objects
for delete
using (bucket_id = 'photos' and true);
